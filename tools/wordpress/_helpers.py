def _elementor_content_collection(content_type: str) -> str:
    normalized = (content_type or "page").strip().lower()
    if normalized in {"page", "pages"}:
        return "pages"
    if normalized in {"post", "posts"}:
        return "posts"
    return normalized


def _elementor_decode_meta_json(value: Any) -> Any:
    if not isinstance(value, str):
        return value
    try:
        return json.loads(value)
    except json.JSONDecodeError:
        return value


def _elementor_encode_json_blob(value: Any, field_name: str) -> str:
    if isinstance(value, (dict, list)):
        return json.dumps(value)
    if not isinstance(value, str):
        raise ValueError(f"{field_name} must be a JSON string, list, or dict")
    try:
        json.loads(value)
    except json.JSONDecodeError as exc:
        raise ValueError(f"{field_name} must be valid JSON") from exc
    return value


def _elementor_is_native_structure(value: Any) -> bool:
    if not isinstance(value, list):
        return False
    supported_types = {"section", "column", "container", "widget"}
    for element in value:
        if not isinstance(element, dict):
            return False
        if element.get("elType") not in supported_types:
            return False
        if not isinstance(element.get("id"), str) or not element.get("id"):
            return False
        if element.get("elType") == "widget" and (not isinstance(element.get("widgetType"), str) or not element.get("widgetType")):
            return False
    return True


def _elementor_validate_native_elements(elements: Any) -> None:
    if not isinstance(elements, list):
        raise ValueError("elementor_data must be a JSON array of native Elementor elements")
    supported_types = {"section", "column", "container", "widget"}
    for element in elements:
        if not isinstance(element, dict):
            raise ValueError("Each Elementor element must be an object")
        el_type = element.get("elType")
        if el_type not in supported_types:
            raise ValueError(
                "elementor_data must use native Elementor element objects with elType values like section, column, container, or widget. "
                "Use elementor_build_page or elementor_preset_* for descriptive section briefs."
            )
        if not isinstance(element.get("id"), str) or not element.get("id"):
            raise ValueError("Each Elementor element must include a non-empty string id")
        if el_type == "widget" and (not isinstance(element.get("widgetType"), str) or not element.get("widgetType")):
            raise ValueError("Each Elementor widget element must include a non-empty widgetType")
        children = element.get("elements") or []
        if not isinstance(children, list):
            raise ValueError("Each Elementor element must store child elements in a list")
        _elementor_validate_native_elements(children)


def _elementor_validate_data_json(elementor_data: Any) -> str:
    encoded = _elementor_encode_json_blob(elementor_data, "elementor_data")
    parsed = json.loads(encoded)
    _elementor_validate_native_elements(parsed)
    return encoded


