def _wp_save_blocks(post_id: int, post_type: str, blocks: list) -> dict:
    collection = _elementor_content_collection(post_type)
    content = _wp_serialize_blocks(blocks)
    updated = _wp().post(f"/wp/v2/{collection}/{post_id}", json={"content": content})
    return {
        "post_id": post_id,
        "post_type": collection,
        "content": content,
        "blocks": _wp_parse_blocks_content(content),
        "post": updated,
    }


def _wp_block_index(index: int, blocks: list) -> int:
    if index < 0 or index >= len(blocks):
        raise IndexError(f"Block index {index} is out of range")
    return index


def _wp_apply_block_operations(blocks: list, operations: list) -> list:
    working = list(blocks)
    for operation in operations or []:
        action = str((operation or {}).get("op") or (operation or {}).get("action") or "").strip().lower()
        if action == "insert":
            insert_at = int((operation or {}).get("position", len(working)))
            insert_at = max(0, min(insert_at, len(working)))
            working.insert(insert_at, operation.get("block") or {})
        elif action == "update":
            index = _wp_block_index(int(operation.get("index")), working)
            current = dict(working[index] or {})
            current["attrs"] = {**(current.get("attrs") or {}), **(operation.get("attrs") or {})}
            if "innerHTML" in operation:
                current["innerHTML"] = operation.get("innerHTML")
            working[index] = current
        elif action == "remove":
            working.pop(_wp_block_index(int(operation.get("index")), working))
        elif action == "move":
            from_index = _wp_block_index(int(operation.get("from_index")), working)
            block = working.pop(from_index)
            to_index = max(0, min(int(operation.get("to_index", len(working))), len(working)))
            working.insert(to_index, block)
        elif action == "replace":
            working[_wp_block_index(int(operation.get("index")), working)] = operation.get("block") or {}
        elif action == "wrap":
            start_index = _wp_block_index(int(operation.get("start_index")), working)
            end_index = _wp_block_index(int(operation.get("end_index")), working)
            if end_index < start_index:
                raise ValueError("end_index must be >= start_index")
            wrapper_name = operation.get("wrapper") or "group"
            wrapper_attrs = operation.get("wrapper_attrs") or {}
            wrapped_blocks = working[start_index:end_index + 1]
            wrapper_block = {
                "blockName": wrapper_name,
                "attrs": wrapper_attrs,
                "innerHTML": _wp_serialize_blocks(wrapped_blocks),
            }
            working[start_index:end_index + 1] = [wrapper_block]
        else:
            raise ValueError(f"Unsupported block batch operation '{action}'")
    return working


def _wp_global_styles_resolution_hint() -> dict:
    try:
        active_theme = _wp().get("/wp/v2/themes", params={"status": "active"})
    except requests.HTTPError as exc:
        active_theme = _unsupported_from_http(exc, "wp/v2 themes controller")
    return {
        "supported": False,
        "reason": "Global styles operations without a concrete global styles id are ambiguous. Use the explicit id-based global styles tools with a verified id from the site.",
        "active_theme": active_theme,
    }


def _elementor_insert_widget(
    page_id: int,
    page_type: str,
    widget_type: str,
    section_index: int = 0,
    column_index: int = 0,
    settings: dict | None = None,
) -> dict:
    _, structure = _elementor_get_document_structure(page_id, page_type)
    target_children = _elementor_target_children(structure, section_index, column_index)
    target_children.append(_elementor_make_widget(widget_type, _elementor_build_widget_settings(widget_type, settings)))
    return _elementor_update_document_structure(page_id, page_type, structure)


def _elementor_upsert_widget(
    page_id: int,
    page_type: str,
    widget_type: str,
    settings: dict | None = None,
    section_index: int = 0,
    column_index: int = 0,
    element_id: str | None = None,
) -> dict:
    if element_id is not None:
        return elementor_update_widget_settings(page_id, element_id, settings or {}, page_type=page_type)
    return _elementor_insert_widget(page_id, page_type, widget_type, section_index, column_index, settings)
