def _elementor_find_element(elements: list, element_id: str) -> dict | None:
    for index, element in enumerate(elements):
        if str(element.get("id")) == str(element_id):
            return {"element": element, "siblings": elements, "index": index}
        found = _elementor_find_element(element.get("elements") or [], element_id)
        if found:
            return found
    return None


def _elementor_target_children(structure: list, section_index: int = 0, column_index: int = 0) -> list:
    if not structure:
        structure.append(_elementor_make_section())
    root_index = max(0, min(section_index, len(structure) - 1))
    root_element = structure[root_index]
    root_type = root_element.get("elType")
    if root_type in {"container", "column"}:
        return root_element.setdefault("elements", [])
    if root_type == "section":
        columns = root_element.setdefault("elements", [])
        if not columns:
            columns.append(_elementor_make_column())
        column_slot = max(0, min(column_index, len(columns) - 1))
        return columns[column_slot].setdefault("elements", [])
    return root_element.setdefault("elements", [])


def _elementor_clone_with_new_ids(element: dict) -> dict:
    cloned = json.loads(json.dumps(element))
    def _reassign_ids(node: dict) -> None:
        node["id"] = _elementor_new_element_id()
        for child in node.get("elements") or []:
            _reassign_ids(child)
    _reassign_ids(cloned)
    return cloned


def _elementor_collect_widgets(elements: list, widgets: list | None = None) -> list:
    if widgets is None:
        widgets = []
    for element in elements:
        if element.get("elType") == "widget":
            widgets.append({
                "id": element.get("id"),
                "widgetType": element.get("widgetType"),
                "settings": element.get("settings") or {},
            })
        _elementor_collect_widgets(element.get("elements") or [], widgets)
    return widgets


def _elementor_merge_element_settings(page_id: int, page_type: str, element_id: str, settings: dict, allowed_types: set[str] | None = None) -> dict:
    _, structure = _elementor_get_document_structure(page_id, page_type)
    found = _elementor_find_element(structure, element_id)
    if not found:
        raise ValueError(f"Element '{element_id}' not found")
    element_type = found["element"].get("elType")
    if allowed_types is not None and element_type not in allowed_types:
        raise ValueError(f"Element '{element_id}' is not one of: {', '.join(sorted(allowed_types))}")
    found["element"]["settings"] = {**(found["element"].get("settings") or {}), **(settings or {})}
    return _elementor_update_document_structure(page_id, page_type, structure)


