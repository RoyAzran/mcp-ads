def _elementor_create_library_template(
    title: str,
    template_type: str = "page",
    content: Any = None,
    page_settings: dict | None = None,
    status: str = "publish",
) -> dict:
    body = {"title": title, "status": status}
    if template_type is not None:
        body["type"] = template_type
    created = _wp().post("/wp/v2/elementor_library", json=body)
    if content is None and page_settings is None:
        template = _elementor_format_document(_elementor_get_library_document(created["id"]))
    else:
        template = elementor_update_page_data(
            created["id"],
            content if content is not None else [],
            type="elementor_library",
            page_settings=page_settings,
        )
    template["template_kind"] = template_type
    return template


def _elementor_format_document(document: dict) -> dict:
    meta = document.get("meta") or {}
    return {
        "id": document.get("id"),
        "type": document.get("type"),
        "status": document.get("status"),
        "slug": document.get("slug"),
        "title": document.get("title"),
        "template": document.get("template"),
        "edit_mode": meta.get("_elementor_edit_mode"),
        "elementor_enabled": meta.get("_elementor_edit_mode") == "builder",
        "elementor_data": _elementor_decode_meta_json(meta.get("_elementor_data")),
        "page_settings": _elementor_decode_meta_json(meta.get("_elementor_page_settings")),
        "meta": meta,
    }


