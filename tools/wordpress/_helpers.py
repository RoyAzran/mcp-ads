def _elementor_make_section(columns: int = 1, settings: dict | None = None) -> dict:
    column_count = max(1, int(columns or 1))
    column_size = max(1, int(100 / column_count))
    return {
        "id": _elementor_new_element_id(),
        "elType": "section",
        "isInner": False,
        "settings": settings or {},
        "elements": [_elementor_make_column(column_size) for _ in range(column_count)],
    }


